-- ── Resolve the project each appraisal's history reaches ──────────────────────────────────────
-- Nearest ancestor wins. Verified on the 2026-08-03 data: every one of these appraisals reaches
-- exactly one project at its nearest depth, so the choice is not arbitrary.
IF OBJECT_ID('tempdb..#Target') IS NOT NULL DROP TABLE #Target;
WITH Walk AS (
    SELECT u.AppraisalNumber, a.Id AS AppraisalId, a.PrevAppraisalId, 0 AS Depth,
           CAST('|' + CAST(a.Id AS varchar(36)) + '|' AS varchar(max)) AS Path
    FROM (SELECT DISTINCT AppraisalNumber FROM #As400Units) u
    JOIN appraisal.Appraisals a ON a.AppraisalNumber = u.AppraisalNumber AND a.IsDeleted = 0

    UNION ALL

    SELECT w.AppraisalNumber, p.Id, p.PrevAppraisalId, w.Depth + 1,
           CAST(w.Path + CAST(p.Id AS varchar(36)) + '|' AS varchar(max))
    FROM Walk w
    JOIN appraisal.Appraisals p ON p.Id = w.PrevAppraisalId AND p.IsDeleted = 0
    WHERE CHARINDEX('|' + CAST(p.Id AS varchar(36)) + '|', w.Path) = 0
),
Reached AS (
    SELECT w.AppraisalNumber, pr.Id AS ProjectId,
           ROW_NUMBER() OVER (PARTITION BY w.AppraisalNumber ORDER BY w.Depth, pr.Id) AS rn
    FROM Walk w
    JOIN appraisal.Projects pr ON pr.AppraisalId = w.AppraisalId
)
SELECT AppraisalNumber, ProjectId
INTO #Target
FROM Reached
WHERE rn = 1
OPTION (MAXRECURSION 0);

-- ── The units that are genuinely new ──────────────────────────────────────────────────────────
IF OBJECT_ID('tempdb..#New') IS NOT NULL DROP TABLE #New;
SELECT
    t.ProjectId,
    u.RoomNumber,
    MAX(u.TowerName)      AS TowerName,
    MAX(u.ModelType)      AS ModelType,
    MAX(u.Floor)          AS Floor,
    MAX(u.SellingPrice)   AS SellingPrice,
    MAX(u.AppraisalValue) AS AppraisalValue,
    ISNULL((SELECT MAX(pu.SequenceNumber) FROM appraisal.ProjectUnits pu WHERE pu.ProjectId = t.ProjectId), 0)
      + ROW_NUMBER() OVER (PARTITION BY t.ProjectId ORDER BY u.RoomNumber) AS SequenceNumber
INTO #New
FROM #As400Units u
JOIN #Target t ON t.AppraisalNumber = u.AppraisalNumber
WHERE NOT EXISTS (SELECT 1
                  FROM appraisal.ProjectUnits pu
                  WHERE pu.ProjectId = t.ProjectId
                    AND (pu.RoomNumber = u.RoomNumber OR pu.CondoRegistrationNumber = u.RoomNumber))
GROUP BY t.ProjectId, u.RoomNumber;

