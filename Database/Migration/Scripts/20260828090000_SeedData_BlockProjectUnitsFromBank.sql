-- ============================================================
-- appraisal.ProjectUnits / ProjectUnitPrices — one-time load of block-project units
-- supplied by the bank for collateral the regulatory export was reporting at zero.
-- Schema: appraisal
--
-- WHY THIS SCRIPT EXISTS
--
-- collateral.vw_RegulatoryExport reports a block-project unit's value from
-- appraisal.ProjectUnitPrices and from nowhere else — the project appraisal itself is a
-- PreAppraisal of the whole development and its figure belongs to the development, not to one
-- unit. Where CAS held no unit row, the export had to send 0. 665 collateral were in that state
-- on the 2026-08-03 AS400 feed.
--
-- The bank returned the missing units on sheet 3 of the Block_Unit_Data_Request workbook
-- (docs/host-collateral-link/, gitignored — it carries real collateral ids). This script loads
-- them. Nothing else in CAS can supply this data: it never passed through an appraisal here.
--
-- WHAT IS LOADED. Room number (the key AS400 names the collateral by), tower, model, floor,
-- selling price, and the appraised value. Tower and model are written to ProjectUnits.TowerName /
-- ModelType as plain text — deliberately NOT as ProjectTowers / ProjectModels rows, because the
-- FKs are nullable, no reader needs them, and inventing master rows for 86 projects from a
-- spreadsheet would be worse data than none.
--
-- WHICH PROJECT A UNIT ATTACHES TO. The same walk the view does: from the appraisal the bank
-- named, back along PrevAppraisalId, to the NEAREST ancestor that owns an appraisal.Projects row.
-- 25 of these appraisals are standalone condo appraisals whose project lives on a parent — the
-- view already looks there, so attaching anywhere else would not be found.
--
-- ONE UNIT PER ROOM, NOT PER COLLATERAL. AS400 issues a collateral id per (collateral, owner),
-- so two owners of one room arrive as two rows. Collateral 104755 and 107808 are both room
-- 168/232 of 66A00041 at the same 6,470,000. One unit row serves both.
--
-- NOT LOADED: usable area. The sheet has no column for it, and the export reads a condo's area
-- from the appraisal's CondoAppraisalDetails rather than from the unit, so a value here would
-- change nothing without a view change as well. 16 units have a non-numeric floor ('12A',
-- '12เอ'); ProjectUnits.Floor is an int, so those land as NULL.
--
-- Idempotent: a room the project already carries is skipped, so re-running is a no-op. Rows whose
-- history reaches no project are skipped and counted rather than failing the migration.
-- ============================================================

SET NOCOUNT ON;

